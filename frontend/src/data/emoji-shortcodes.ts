/** All shortcodes with colons, sorted by length descending for prefix matching */
export const SHORTCODES_SORTED = [...EMOJI_SHORTCODES]
  .map((s) => ({ ...s, shortcode: `:${s.shortcode}:` }))
  .sort((a, b) => b.shortcode.length - a.shortcode.length);

/** Filter shortcodes by prefix (e.g. ":thu" matches ":thumbsup:") */
export function filterEmojiByPrefix(prefix: string): Array<{ shortcode: string; emoji: string }> {
  const q = prefix.toLowerCase().replace(/^:/, "").replace(/:$/, "").trim();
  if (!q) return EMOJI_SHORTCODES.slice(0, 12);
  return EMOJI_SHORTCODES.filter((s) => s.shortcode.toLowerCase().startsWith(q)).slice(0, 12);
}
